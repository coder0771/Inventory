const NORM = (s) => s.replace(/\s+/g, " ").trim();
const LOWER = {};
Object.keys(DICT).forEach((k) => { LOWER[k.toLowerCase()] = DICT[k]; });
const IDX = { hi: 0, mr: 1 };
// beginning of a dynamic text whose ending is a name, number or message (translated part + the rest kept as is)
const PREFIXES = ["Send WhatsApp message to", "Already in Quotations as", "Task submitted to", "Monthly salary -", "Record payment -", "Log call with",
  "OTP sent to", "Notes -", "Written by"].sort((a, b) => b.length - a.length);
const SPLIT = /^([^A-Za-z]*)([\s\S]*?)([\s:*.…!]*(?:\(\d+\))?[\s:*.…!]*)$/;
function look(core, lang) {
  const k = NORM(core), v = DICT[k] || LOWER[k.toLowerCase()];
  return v ? v[IDX[lang]] : null;
}
function translate(text, lang) {
  if (lang === "en" || !text || !/[A-Za-z]{2}/.test(text)) return text;
  const m = text.match(SPLIT);
  if (!m) return text;
  const pre = m[1], core = m[2], post = m[3];
  if (!core) return text;
  let v = look(core, lang);
  if (v !== null) return pre + v + post;
  for (const p of PREFIXES) {
    if (core === p || core.startsWith(p + " ")) { const t = look(p, lang); if (t) return pre + t + core.slice(p.length) + post; }
  }
  const i = core.indexOf(": "); // "Could not save: <reason>"  ->  translate the part before the colon
  if (i > 0) { const t = look(core.slice(0, i), lang); if (t) return pre + t + core.slice(i) + post; }
  return text;
}
