export function initI18n({ db, doc, getDoc, setDoc }) {
  const LS = "pi_lang";
  const devLang = () => { try { const v = localStorage.getItem(LS); return IDX[v] !== undefined || v === "en" ? v : "en"; } catch (e) { return "en"; } };
  let lang = "en", uid = null, titleEn = document.title;
  const SKIP = new Set(["SCRIPT", "STYLE", "TEXTAREA", "CODE", "PRE", "NOSCRIPT"]);
  const skip = (el) => { for (let e = el; e; e = e.parentElement) { if (SKIP.has(e.tagName) || (e.classList && e.classList.contains("notr"))) return true; } return false; };

  function doText(n) {
    if (!n.parentElement || skip(n.parentElement)) return;
    const cur = n.nodeValue;
    if (n.__tr === undefined || cur !== n.__tr) n.__en = cur; // the app wrote new English text
    const out = translate(n.__en, lang);
    n.__tr = out;
    if (out !== cur) n.nodeValue = out;
  }
  function doAttrs(el) {
    if (!el.getAttribute || skip(el)) return;
    for (const a of ["placeholder", "title"]) {
      if (!el.hasAttribute(a)) continue;
      const cur = el.getAttribute(a);
      el.__a = el.__a || {};
      const rec = el.__a[a], en = rec && cur === rec.tr ? rec.en : cur, out = translate(en, lang);
      el.__a[a] = { en, tr: out };
      if (out !== cur) el.setAttribute(a, out);
    }
  }
  function walk(root) {
    if (!root) return;
    if (root.nodeType === 3) return doText(root);
    if (root.nodeType !== 1) return;
    doAttrs(root);
    const w = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let n;
    while ((n = w.nextNode())) n.nodeType === 3 ? doText(n) : doAttrs(n);
  }
  const obs = new MutationObserver((muts) => {
    for (const m of muts) {
      if (m.type === "childList") m.addedNodes.forEach(walk);
      else if (m.type === "characterData") { if (m.target.nodeValue !== m.target.__tr) doText(m.target); }
      else if (m.type === "attributes") { const el = m.target, rec = el.__a && el.__a[m.attributeName]; if (!rec || el.getAttribute(m.attributeName) !== rec.tr) doAttrs(el); }
    }
  });

  function apply(code) {
    lang = IDX[code] !== undefined ? code : "en";
    document.documentElement.lang = lang;
    obs.disconnect();
    walk(document.body); // translate (or restore English) everything already on screen
    document.title = translate(titleEn, lang);
    if (lang !== "en") obs.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["placeholder", "title"] });
    const pick = document.getElementById("langPick");
    if (pick && pick.value !== lang) pick.value = lang;
  }
  async function choose(code) {
    apply(code);
    if (uid) { // logged in: save for THIS person only
      try { await setDoc(doc(db, "userPrefs", uid), { lang, updatedAt: Date.now() }, { merge: true }); } catch (e) { console.warn("Language not saved to the account", e); }
    } else { try { localStorage.setItem(LS, lang); } catch (e) {} } // login screen: remembered on this phone
  }
  // called when someone logs in (uid) or out (null)
  async function onUser(newUid) {
    uid = newUid || null;
    if (!uid) return apply(devLang());
    try {
      const s = await getDoc(doc(db, "userPrefs", uid));
      const saved = s.exists() && s.data().lang;
      if (saved) apply(saved);
      else { apply(devLang()); if (lang !== "en") await setDoc(doc(db, "userPrefs", uid), { lang, updatedAt: Date.now() }, { merge: true }); }
    } catch (e) { apply(devLang()); }
  }

  // the switch, on every screen (bottom left)
  const box = document.createElement("div");
  box.id = "langBox"; box.className = "lang-box notr";
  box.innerHTML = '<span aria-hidden="true">🌐</span><select id="langPick" aria-label="Language / भाषा"><option value="en">English</option><option value="hi">हिंदी</option><option value="mr">मराठी</option></select>';
  document.body.appendChild(box);
  box.querySelector("select").addEventListener("change", (e) => choose(e.target.value));
  apply(devLang());
  window.I18N = { choose, onUser, current: () => lang, t: (s) => translate(s, lang) };
  return { onUser, choose };
}
